    def _compile_latex(self, tex_file: Path) -> Optional[Path]:
        """
        Compile LaTeX to PDF using pdflatex.

        Args:
            tex_file: Path to .tex file

        Returns:
            Path to generated PDF, or None if compilation failed
        """
        try:
            # Run pdflatex twice for references
            for _ in range(2):
                result = subprocess.run(
                    ['pdflatex', '-interaction=nonstopmode',
                     '-output-directory', str(tex_file.parent),
                     str(tex_file)],
                    capture_output=True,
                    text=True,
                    timeout=30
                )

                if result.returncode != 0:
                    print(f"pdflatex error: {result.stderr}")
                    return None

            pdf_file = tex_file.with_suffix('.pdf')

            if pdf_file.exists():
                print(f"PDF generated: {pdf_file}")
                return pdf_file
            else:
                print("PDF file not created")
                return None

        except FileNotFoundError:
            print("pdflatex not found. Install TeX Live or MiKTeX.")
            print("The .tex file has been saved and can be compiled manually.")
            return None
        except subprocess.TimeoutExpired:
            print("LaTeX compilation timeout")
            return None
        except Exception as e:
            print(f"Compilation error: {e}")
            return None


