"""
LaTeX Documentation Generator

Automatically generates LaTeX documentation from simulation results,
BCI data analysis, and system configurations.
"""

from typing import List, Dict, Tuple, Optional, Any
import numpy as np
from datetime import datetime
from pathlib import Path
import subprocess


class LaTeXDocumentGenerator:
    """
    Generate comprehensive LaTeX documentation for Multi-Heart-Model simulations.
    """

    def __init__(self, output_dir: str = "reports"):
        """
        Initialize LaTeX generator.

        Args:
            output_dir: Directory for output files
        """
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(exist_ok=True, parents=True)

        self.preamble = r"""\documentclass[12pt,letterpaper]{article}
\usepackage[utf8]{inputenc}
\usepackage{amsmath}
\usepackage{amsfonts}
\usepackage{amssymb}
\usepackage{graphicx}
\usepackage{float}
\usepackage{booktabs}
\usepackage{hyperref}
\usepackage{listings}
\usepackage{xcolor}
\usepackage{geometry}
\geometry{margin=1in}

% Code listing style
\lstset{
    basicstyle=\ttfamily\small,
    keywordstyle=\color{blue},
    commentstyle=\color{gray},
    stringstyle=\color{red},
    numbers=left,
    numberstyle=\tiny,
    breaklines=true,
    frame=single
}

% Custom commands
\newcommand{\vect}[1]{\boldsymbol{#1}}
\newcommand{\deriv}[2]{\frac{d#1}{d#2}}
\newcommand{\pderiv}[2]{\frac{\partial #1}{\partial #2}}

\title{Multi-Heart-Model Simulation Report}
\author{Generated Automatically}
\date{\today}

\begin{document}
\maketitle
\tableofcontents
\newpage
"""

        self.conclusion = r"""
\section{Conclusion}

This report was automatically generated by the Multi-Heart-Model framework,
documenting the complete simulation configuration, results, and analysis.

\end{document}
"""

    def generate_full_report(self, simulation_data: Dict[str, Any],
                            bci_data: Optional[Dict[str, Any]] = None,
                            figures_dir: Optional[Path] = None) -> str:
        """
        Generate complete LaTeX report.

        Args:
            simulation_data: Dictionary with simulation configuration and results
            bci_data: Optional BCI integration data
            figures_dir: Directory containing figure files

        Returns:
            Path to generated PDF file
        """
        # Start document
        content = [self.preamble]

        # Abstract
        content.append(self._generate_abstract(simulation_data))

        # Model description
        content.append(self._generate_model_description())

        # Configuration
        content.append(self._generate_configuration_section(simulation_data))

        # Results
        content.append(self._generate_results_section(simulation_data, figures_dir))

        # BCI integration (if applicable)
        if bci_data:
            content.append(self._generate_bci_section(bci_data))

        # Analysis
        content.append(self._generate_analysis_section(simulation_data))

        # Statistical summary
        content.append(self._generate_statistics_section(simulation_data))

        # Conclusion
        content.append(self.conclusion)

        # Write to file
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        tex_file = self.output_dir / f"report_{timestamp}.tex"

        with open(tex_file, 'w') as f:
            f.write('\n'.join(content))

        print(f"LaTeX file generated: {tex_file}")

        # Compile to PDF
        pdf_file = self._compile_latex(tex_file)

        return str(pdf_file)

    def _generate_abstract(self, data: Dict[str, Any]) -> str:
        """Generate abstract section."""
        duration = data.get('simulation_duration', 0)
        n_samples = data.get('n_samples', 0)

        return r"""
\begin{abstract}
This report documents a simulation of the Heart-Brain Coupling Model (HBCM),
a multi-domain physiological modeling platform integrating bidirectional
neural-cardiac interactions. The simulation ran for %.2f seconds with %d
timesteps, capturing the complex dynamics of coupled oscillatory systems
representing neural (FitzHugh-Nagumo) and cardiac (Van der Pol) subsystems.
\end{abstract}
\newpage
""" % (duration, n_samples)

    def _generate_model_description(self) -> str:
        """Generate mathematical model description."""
        return r"""
\section{Mathematical Model}

\subsection{FitzHugh-Nagumo Neural Model}

The neural subsystem is modeled using the FitzHugh-Nagumo equations, a simplified
representation of neuronal excitability:

\begin{align}
\deriv{v}{t} &= v - \frac{v^3}{3} - w + I_{\text{ext}} + I_{\text{cardiac}} \\
\deriv{w}{t} &= \frac{1}{c}(v + a - bw)
\end{align}

where:
\begin{itemize}
    \item $v$ is the membrane voltage
    \item $w$ is the recovery variable
    \item $a, b, c$ are model parameters
    \item $I_{\text{ext}}$ is external stimulus
    \item $I_{\text{cardiac}}$ is the input from cardiac system
\end{itemize}

\subsection{Van der Pol Cardiac Model}

The cardiac subsystem employs the Van der Pol oscillator:

\begin{align}
\deriv{x}{t} &= y + I_{\text{neural}} \\
\deriv{y}{t} &= -\omega^2 x - \mu(x^2 - 1)y
\end{align}

where:
\begin{itemize}
    \item $x$ is the oscillator position (representing cardiac activity)
    \item $y$ is the velocity
    \item $\mu$ controls the degree of nonlinearity
    \item $\omega$ is the natural frequency
    \item $I_{\text{neural}}$ is the input from neural system
\end{itemize}

\subsection{Bidirectional Coupling}

The coupling between systems is implemented with time delays:

\begin{align}
I_{\text{cardiac}}(t) &= g_{nc} \cdot v(t - \tau_{nc}) \\
I_{\text{neural}}(t) &= g_{cn} \cdot x(t - \tau_{cn})
\end{align}

where $g_{nc}, g_{cn}$ are coupling gains and $\tau_{nc}, \tau_{cn}$ are
communication delays representing physiological signal propagation times.

"""

